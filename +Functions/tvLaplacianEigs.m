function eigsDtD = tvLaplacianEigs(m, n)
%TV_LAPLACIAN_EIGS 周期二维差分正规算子 D'*D 的特征值。
%   EIGSDTD = TV_LAPLACIAN_EIGS(M, N) 返回 M×N 的傅里叶特征值数组，
%   该特征值对应于周期前向有限差分所构成的正规算子 D'*D。
%
%   输入参数:
%       m,n - 图像的高度和宽度（行数、列数）。
%
%   输出参数:
%       eigsDtD - M×N 的特征值矩阵，供 TV 子问题的频域线性求解器使用。

% 生成二维网格索引：
%   jj 为列索引，取值 0..n-1，对应于水平频率分量；
%   ii 为行索引，取值 0..m-1，对应于垂直频率分量。
% meshgrid 第一个参数对应列(x)，第二个参数对应行(y)，
% 故 jj 沿列方向变化，ii 沿行方向变化，与图像尺寸 m(行)×n(列) 匹配。
[jj, ii] = meshgrid(0:n-1, 0:m-1);

% 计算 D'*D 算子的特征值。
% 对于二维周期前向差分，其伴随为后向差分，两者合成后得到
% 离散拉普拉斯算子，其傅里叶特征值为：
%   λ(i,j) = 4 - 2·cos(2π·i/m) - 2·cos(2π·j/n)
% 其中 i 为垂直方向频率索引，j 为水平方向频率索引。
% 该公式来源于对水平方向和垂直方向二阶差分算子的对角化。
% 注意：这里没有负号，因为在 TV 正则化中通常直接使用该特征值谱。
eigsDtD = 4 - 2*cos(2*pi*ii/m) - 2*cos(2*pi*jj/n);
end
