function x = tvAdjoint(d, m, n)
%TV_ADJOINT 伴随算子：周期前向有限差分的伴随变换。
%   X = TV_ADJOINT(D, M, N) 计算 Functions.tvForward 所实现的线性算子 D 的伴随 D'*DVAR，
%   其中 DVAR 是一个堆叠向量 [d_vertical; d_horizontal]。
%
%   输入参数:
%       d   - 尺寸为 2*M*N x 1 的堆叠差分向量（先垂直分量，后水平分量）。
%       m,n - 图像的高度和宽度（行数、列数）。
%
%   输出参数:
%       x   - 尺寸为 M*N x 1 的伴随计算结果（梯度域的伴随投影回图像域）。

% 计算图像总像素数
N = m * n;

% 从输入向量 d 中分离垂直差分分量，并重塑为 m x n 矩阵
% d(1:N) 对应周期前向有限差分的垂直部分
d1 = reshape(d(1:N), m, n);

% 分离水平差分分量，重塑为 m x n 矩阵
% d(N+1:end) 对应周期前向有限差分的水平部分
d2 = reshape(d(N+1:end), m, n);

% 计算伴随作用：
% 垂直方向：周期后向差分（向上循环移位后减原值）
% circshift(d1, 1, 1) 将 d1 沿着第1维（行）向上循环移动1位，
% 相当于对垂直分量实施周期后向差分，即 (D_v^T * d1)
% 注意：由于原始前向差分在垂直方向是 d1(i,j) = x(i+1,j) - x(i,j)（周期），
% 其伴随为 circshift(d1,1,1) - d1。
%
% 水平方向：周期后向差分（向左循环移位后减原值）
% circshift(d2, 1, 2) 将 d2 沿着第2维（列）向左循环移动1位，
% 相当于对水平分量实施周期后向差分，即 (D_h^T * d2)
% 同样，原始前向差分在水平方向是 d2(i,j) = x(i,j+1) - x(i,j)（周期），
% 其伴随为 circshift(d2,1,2) - d2。
%
% 两部分相加得到最终的伴随结果（梯度域的线性组合反投影到图像域）
x = circshift(d1, 1, 1) - d1 + circshift(d2, 1, 2) - d2;

% 将矩阵结果拉直为 M*N x 1 的列向量，与输入图像的向量化格式保持一致
x = x(:);
end
