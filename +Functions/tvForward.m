function d = tvForward(x, m, n)
%TV_FORWARD 计算周期性二维前向有限差分。
%   D = TV_FORWARD(X, M, N) 将向量 X 重塑为 M×N 的图像，并返回堆叠的
%   垂直和水平周期前向差分。
%
%   输入参数:
%       x   - 尺寸为 M*N x 1 的图像向量（列向量）。
%       m,n - 图像的高度和宽度（行数、列数）。
%
%   输出参数:
%       d   - 尺寸为 2*M*N x 1 的向量，按 [垂直差分; 水平差分] 堆叠。

% 将输入的图像向量重塑为 m×n 的矩阵，便于沿行列方向进行差分运算
X = reshape(x, m, n);

% 计算垂直方向上的周期前向差分
% circshift(X, -1, 1) 将矩阵沿第 1 维（行）向下循环移动 1 行
% 这样 X 的第 i 行变为原来的第 i-1 行（周期边界），即 X_{i,j} ← X_{i+1,j}
% 减去原始 X 得到垂直差分：d1(i,j) = X(i+1,j) - X(i,j) （周期性）
d1 = circshift(X, -1, 1) - X;

% 计算水平方向上的周期前向差分
% circshift(X, -1, 2) 将矩阵沿第 2 维（列）向右循环移动 1 列
% 这样 X 的第 j 列变为原来的第 j-1 列（周期边界），即 X_{i,j} ← X_{i,j+1}
% 减去原始 X 得到水平差分：d2(i,j) = X(i,j+1) - X(i,j) （周期性）
d2 = circshift(X, -1, 2) - X;

% 将两个差分矩阵分别拉直为列向量，并垂直拼接成一个 2*M*N 的向量
% 顺序是先垂直差分后水平差分，与 Functions.tvAdjoint 中的分解顺序一致
d = [d1(:); d2(:)];
end
